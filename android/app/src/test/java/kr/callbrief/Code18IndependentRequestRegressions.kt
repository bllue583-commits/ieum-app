    private fun updateResult(id:String,base:ByteArray,state:String,rev:Long):ByteArray {
        val m=StrictJson.`object`(StrictJson.parse(base)).toMutableMap();m["state"]=state;m["resultRevision"]=rev
        if(state=="ERROR")m["error"]=mapOf("code" to "PUBLIC_SYNTHETIC_ERROR","message" to "codec fixture only")
        if(state=="PROPOSAL") {
            val text="공개 합성 전사 · 모델 실행 없음"
            m["stt"]=mapOf("execution" to "FIXTURE","text" to text,"textSha" to DriveRelay.sha256(text.toByteArray()),"evidenceRef" to "PUBLIC_FIXTURE_ONLY")
        }
        m["resultDigest"]=WireV0Codec.digest("result",m)
        return StrictJson.bytes(m).also { drive.bytes[id]=it;drive.versions[id]=drive.versions.getValue(id)+1 }
    }
    @Test fun N01DuplicateOldPendingCannotEraseNewerError():Unit=io {
        pipeline().use { p->AnalysisRequestFlow(context,fixtureSession,{NativePort(p)}).use { flow->
            val id=flow.prepare(recording,snap());assertEquals("SENT",flow.submit(id));val job=p.jobs().single();val pending=drive.bytes.getValue(job.resultId).clone()
            assertEquals("PENDING",flow.poll(id));updateResult(job.resultId,pending,"ERROR",1);assertEquals("ERROR",flow.poll(id))
            drive.bytes[job.resultId]=pending;drive.versions[job.resultId]=drive.versions.getValue(job.resultId)+1
            val actual=flow.poll(id);val head=db().use { it.query("SELECT result_revision FROM drive_profiles_heads").single()["result_revision"] }
            proof("N01","workflowState" to actual,"head" to head,"nativeRemoteState" to p.jobs().single().remoteState,"manualStatus" to snap().getString("manual_status"))
            assertEquals("Receipt DUPLICATE at revision0 must not erase the accepted error head1","ERROR",actual)
        } }
    }
