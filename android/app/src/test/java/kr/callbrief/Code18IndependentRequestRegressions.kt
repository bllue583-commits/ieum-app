    private fun proof(name:String,vararg pairs:Pair<String,Any?>) {
        val o=JSONObject().put("scope","INDEPENDENT_API35_HOST_NATIVE_GRAPHICS_SQLITE_FAKE_DRIVE_NO_ACCOUNT_PROVIDER")
